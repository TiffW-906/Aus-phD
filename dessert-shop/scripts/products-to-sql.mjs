// Prints supabase/seed.sql from data/products.json: `npm run seed:sql`.
// Products start as 可預訂 (preorder, 3 days); the seller switches them in /admin/products.
import { readFileSync } from 'node:fs';

const products = JSON.parse(readFileSync(new URL('../data/products.json', import.meta.url), 'utf8'));
const str = (s) => `'${String(s).replaceAll("'", "''")}'`;
const arr = (a) => `array[${a.map(str).join(', ')}]::text[]`;

console.log('-- Generated by scripts/products-to-sql.mjs from data/products.json. Do not edit by hand.');
console.log('insert into public.products (id, name, category, price, unit_note, temp_type, flavors, sort_order) values');
console.log(
  products
    .map((p, i) => `  (${str(p.id)}, ${str(p.name)}, ${str(p.category)}, ${p.price}, ${str(p.unit_note)}, ${str(p.temp_type)}, ${arr(p.flavors)}, ${(i + 1) * 10})`)
    .join(',\n') +
    '\non conflict (id) do update set name = excluded.name, category = excluded.category, price = excluded.price,' +
    '\n  unit_note = excluded.unit_note, temp_type = excluded.temp_type, flavors = excluded.flavors, sort_order = excluded.sort_order;'
);
